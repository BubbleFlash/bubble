type Props = {
  icon: keyof typeof paths | "settings";
  label: string;
  className?: string;
} & ({ to: string } | { onClick?: () => void; disabled?: boolean; type?: "button" | "submit" });

export default function ProfileAction({
  icon,
  label,
  className = "btn btn-outline",
  ...action
}: Props) {
  const symbol = icon === "settings" ? <NavigationIcon name="settings" size={24} /> : (
    <ProfileActionIcon icon={icon} />
  );
  const classes = `profile-action ${className}`;
  return (
    <span className="profile-action-wrap">
      {"to" in action ? (
        <Link className={classes} to={action.to} aria-label={label}>
          {symbol}
        </Link>
      ) : (
        <button className={classes} aria-label={label} {...action} type={action.type ?? "button"}>
          {symbol}
        </button>
      )}
      <span className="profile-action-tooltip" aria-hidden="true">
        {label}
      </span>
    </span>
  );
}
